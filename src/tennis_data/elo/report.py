"""Markdown evaluation report for the Elo backtest (no timestamps; reproducible)."""

from __future__ import annotations

from pathlib import Path

import polars as pl

from tennis_data.elo.backtest import GLOBAL, SURFACE
from tennis_data.elo.config import EloConfig
from tennis_data.reporting.quality import _markdown_table


def _table(df: pl.DataFrame, digits: int = 4, limit: int | None = None) -> str:
    def fmt(v):
        return round(v, digits) if isinstance(v, float) else v

    return _markdown_table(df.columns, [tuple(fmt(v) for v in r) for r in df.rows()], limit=limit)


def _verdict(c: dict) -> str:
    lo, hi = c["log_loss_diff_ci_low"], c["log_loss_diff_ci_high"]
    if hi < 0:
        return "lower log loss than global Elo; the 95% interval excludes zero"
    if lo > 0:
        return "higher log loss than global Elo; the 95% interval excludes zero"
    return "no log-loss difference from global Elo distinguishable at 95% (interval contains zero)"


def render(cfg: EloConfig, result: dict) -> str:
    s = result["summary"]
    t = result["tables"]
    test, val = result["test"], result["validation"]
    sel = s["selected"]

    def params_line(name: str) -> str:
        p = sel[name]["params"]
        k = (
            f"K = {p['k_constant']:g}"
            if p["k_mode"] == "constant"
            else (f"K(n) = {p['k_numerator']:g} / (n + {p['k_offset']:g})^{p['k_shape']:g}")
        )
        extra = (
            ""
            if name == GLOBAL
            else (
                f", surface_init = {p['surface_init']}, shrinkage m = {p['shrinkage_matches']:g}, carpet = {p['carpet_policy']}"
            )
        )
        return f"- `{name}`: {k}{extra} (configuration_hash `{sel[name]['configuration_hash']}`)"

    comp_rows = [
        (name, c["rows"], c["clusters"], round(c["log_loss_diff"], 5), round(c["log_loss_diff_ci_low"], 5),
         round(c["log_loss_diff_ci_high"], 5), round(c["brier_diff"], 5), round(c["brier_diff_ci_low"], 5),
         round(c["brier_diff_ci_high"], 5))
        for name, c in s["test_comparisons"].items()
    ]  # fmt: skip
    verdicts = [f"- `{name}`: {_verdict(c)}." for name, c in s["test_comparisons"].items()]
    excl = t["exclusions"]
    test_n = test["overall"].filter(pl.col("model") == GLOBAL)["n"][0]
    val_n = val["overall"].filter(pl.col("model") == GLOBAL)["n"][0]

    grid = t["tuning_grid"]
    top = {
        m: grid.filter(pl.col("model") == m).sort("log_loss").head(8).drop("model", "mean_predicted_a", "observed_a")
        for m in (GLOBAL, SURFACE)
    }
    ece = pl.DataFrame({"model": list(s["test_ece"]), "expected_calibration_error": list(s["test_ece"].values())})

    lines = [
        "# Elo backtest: ATP singles",
        "",
        "Generated by `tennis-data elo-backtest`. All numbers are computed from the pipeline outputs; nothing is entered "
        "by hand. No timestamps, so the report is reproducible.",
        "",
        f"- Source commit `{s['source_commit']}`, model version `{s['model_version']}`",
        f"- Validation (tuning) period: prediction batches from {s['periods']['validation'][0]} to before "
        f"{s['periods']['validation'][1]} ({val_n} matches). Earlier batches are rating warm-up only.",
        f"- Test (out-of-sample) period: {s['periods']['test'][0]} to {s['periods']['test'][1]} ({test_n} matches). "
        "No parameter was chosen using test outcomes.",
        "",
        "## Chronology (read this first)",
        "",
        "The source has **no match dates**; only each event's start date. Matches are therefore grouped into weekly "
        f"batches running from {cfg.chronology.week_start.capitalize()} 00:00 to six days later, by `tournament_date`. "
        "All predictions in a batch use the ratings frozen at the batch start; results update ratings only when the "
        "batch closes. Multi-week events ("
        + "; ".join(
            f"levels {'/'.join(r.levels)}"
            + (f" with draw >= {r.min_draw_size}" if r.min_draw_size else "")
            + f": {r.weeks} weeks"
            for r in cfg.chronology.multi_week
        )
        + ") update only when their last batch closes. A match's prediction therefore never uses its own result, "
        "nor any result from its own event or from later batches. Weekly batching is an approximation: ratings can be "
        "up to a week (two for long events) staler than a match-by-match replay with true dates would allow.",
        "",
        "Within a batch close, all results are applied simultaneously from the frozen state (order-independent, "
        "zero-sum); see `docs/elo.md`.",
        "",
        "## Selected parameters (chosen on validation log loss)",
        "",
        params_line(GLOBAL),
        params_line(SURFACE),
        "",
        "## Test-period results (out of sample)",
        "",
        "All models are scored on the identical set of test matches (completed matches in the rating pool). "
        "`*_with_retirements` is the sensitivity experiment: same parameters, retirements added to the rating updates "
        "(not to the scored targets).",
        "",
        _table(t["test_overall"].drop("mean_predicted_a", "observed_a")),
        "",
        _table(ece, 5),
        "",
        "### Paired comparison against global Elo (test period)",
        "",
        "Difference = model minus global Elo on the same matches (negative = better). 95% intervals from a bootstrap "
        f"over weekly prediction batches ({cfg.evaluation.bootstrap_samples} resamples, seed "
        f"{cfg.evaluation.bootstrap_seed}).",
        "",
        _markdown_table(
            [
                "comparison",
                "matches",
                "batches",
                "log_loss_diff",
                "ll_ci_low",
                "ll_ci_high",
                "brier_diff",
                "brier_ci_low",
                "brier_ci_high",
            ],
            comp_rows,
        ),
        "",
        *verdicts,
        "",
        "### By surface (test)",
        "",
        _table(t["test_by_surface"].drop("mean_predicted_a", "observed_a")),
        "",
        "### By tournament level (test)",
        "",
        _table(t["test_by_level"].drop("mean_predicted_a", "observed_a")),
        "",
        "### Calibration (test, P(player A wins) in equal-width bins)",
        "",
        _table(t["test_calibration"].filter(pl.col("model").is_in([GLOBAL, SURFACE]))),
        "",
        "## Validation-period results (in-sample for tuning; not evidence of out-of-sample skill)",
        "",
        _table(t["validation_overall"].drop("mean_predicted_a", "observed_a")),
        "",
        "## Evaluated and excluded matches",
        "",
        "`eligible_target` rows are predicted (and scored when in the validation/test period). Excluded validated rows "
        "keep their reason; quarantined rows never enter the Elo model.",
        "",
        _table(excl),
        "",
        "## Tuning grid (best 8 per model by validation log loss; full grid in `tables/tuning_grid.csv`)",
        "",
        f"### {GLOBAL}",
        "",
        _table(top[GLOBAL].drop("surface_init", "carpet_policy", "shrinkage_matches"), 5),
        "",
        f"### {SURFACE}",
        "",
        _table(top[SURFACE], 5),
        "",
    ]
    return "\n".join(lines)


def write_report(cfg: EloConfig, result: dict) -> Path:
    path = cfg.reports_dir / "evaluation_report.md"
    path.write_text(render(cfg, result))
    return path
