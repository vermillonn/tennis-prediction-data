"""Phase 5A operational reports, rendered from ``results.json`` (+ run metadata, state check, benchmark).

Every report keeps six kinds of statement apart: verified observations (real records ingested or real requests
made), results inferred from source metadata, fixture-only tests, unverified provider capabilities, blockers, and
recommended next actions. Synthetic records are never reported as ingested matches.
"""

from __future__ import annotations

from pathlib import Path

ALLOW_HOSTS = {
    "sportradar_tennis": "api.sportradar.com", "api_tennis": "api.api-tennis.com", "tennisdata_app": "tennisdata.app",
    "rapidapi_tennisapi": "tennisapi1.p.rapidapi.com", "tennis_data_co_uk": "www.tennis-data.co.uk",
    "tml_website": "stats.tennismylife.org",
}  # fmt: skip
BLOCKER_KIND = {"NETWORK_BLOCKED": "network restriction", "DNS_FAILURE": "network restriction (DNS)",
                "CREDENTIALS_ABSENT": "missing credentials", "AUTH_REJECTED": "credentials refused / subscription",
                "RATE_LIMITED": "provider rate limit", "NOT_FOUND": "source no longer publishes the data",
                "SCHEMA_MISMATCH": "schema incompatibility", "NOT_PROBED": "licensing / terms"}  # fmt: skip


def f(x, nd=3):
    if x is None:
        return "n/a"
    return f"{x:.{nd}f}" if isinstance(x, float) else str(x)


def tbl(head: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + [
        "| " + " | ".join(str(c) for c in r) + " |" for r in rows
    ]


def header(title: str, res: dict, meta: dict) -> list[str]:
    return [f"# {title}", "", f"Generated by `tennis-data ops-run` for as-of date **{res['as_of']}** (Phase 5A). "
            f"Provider probes ran at {meta.get('probed_at') or 'n/a'} (UTC, operational metadata).", ""]  # fmt: skip


def provider_access(res, meta, cfg) -> str:
    a = res["access"]["results"]
    L = header("Provider access and connectivity", res, meta)
    L += ["## Verified observations (one real request per provider from this environment)", ""]
    L += tbl(["provider", "kind", "status", "HTTP", "credentials", "verified data"],
             [[r["provider"], r["kind"], r["status"], r["http_status"] or "-",
               f"{r['credentials']} (`{r['credential_env']}`)" if r["credential_env"] else "not required",
               (f"{r['data']['rows']} rows, {r['data']['first_tourney_date']}–{r['data']['last_tourney_date']}, "
                f"{r['data']['rows_with_serve_stats']} with serve stats") if r.get("data") and r["data"].get("ok") else "-"]
              for r in a])  # fmt: skip
    L += ["", "A provider is **verified** only when a data request returned records whose schema was inspected "
          "(`DATA_VERIFIED`). Verified sources: " + (", ".join(res["access"]["verified_sources"]) or "none") + ".", "",
          "What the verified sources contain (all observed):", "",
          "- `archive_mirror` (the pinned Phase 1 archive repository): its `main` equals the pinned commit and ends "
          "with tournaments starting 2026-05-25. It holds **nothing after the archive** and cannot fill the gap.",
          "- `tml_github` (TML-Database on GitHub): 2025 and 2026-01-02 to 2026-01-21 only. Its README says the "
          "GitHub copy is kept for reference and the live database moved to stats.tennismylife.org, which is "
          "blocked here. It holds **nothing in the gap**, but it overlaps the archive and was used for the "
          "statistical compatibility and identity studies.",
          "- `sackmann_upstream` (JeffSackmann/tennis_atp): HTTP 404 for raw files; git asks for credentials. The "
          "repository is not publicly reachable from here.", "",
          "## Unverified provider capabilities (from configuration and documentation, not observed)", ""]  # fmt: skip
    L += tbl(["provider", "results", "serve statistics", "schedules", "actual start", "corrections", "terms"],
             [[p.name, p.offers.get("historical_results", "?"), p.offers.get("serve_statistics", "?"),
               p.offers.get("schedules", "?"), p.offers.get("actual_start", "?"), p.offers.get("corrections", "?"),
               p.terms] for p in cfg.providers])  # fmt: skip
    L += ["", "## Blockers, by kind", ""]
    kinds: dict = {}
    for r in a:
        if r["status"] in BLOCKER_KIND:
            kinds.setdefault(BLOCKER_KIND[r["status"]], []).append(r["provider"])
    L += [f"- **{k}**: {', '.join(v)}" for k, v in sorted(kinds.items())]
    L += ["- **missing statistical coverage**: tennis-data.co.uk (results and odds only, no serve statistics), "
          "by its own documentation",
          "- **no source in the gap**: every reachable source ends on or before 2026-05-25", "",
          "## Minimum action needed from the repository owner", "",
          "Network access is set per environment (environment settings → Network access → allowed domains; "
          "https://code.claude.com/docs/en/cloud-environments#network-access). Credentials are added as "
          "environment variables of the environment and are never committed. Any one of the following unblocks "
          "the gap backfill:", "",
          "1. **Licensed API (results + statistics + schedules + actual start).** For example Sportradar Tennis: "
          "allow `api.sportradar.com` and set `SPORTRADAR_API_KEY` (a trial key is limited and commercial use "
          "needs a contract). Similar for api-tennis.com (`api.api-tennis.com`, `API_TENNIS_KEY`) or RapidAPI "
          "(`tennisapi1.p.rapidapi.com`, `RAPIDAPI_KEY`). The response layouts are still unverified and must be "
          "checked against real responses before use (Phase 4A `NotVerifiedError`).",
          "2. **Authorized file export.** Place a Sackmann-format CSV export you are licensed to use (for example "
          "from the TML website, if its terms permit) in the workspace and import it with "
          "`tennis-data prospective-import <file> --format sackmann_csv`, if its IDs are archive IDs. Otherwise "
          "convert it with the TML converter (ATP codes).",
          "3. **Results-only source.** Allow `www.tennis-data.co.uk` for completed-match results (no serve "
          "statistics). Elo updates are possible; serve/return state would stay missing for the gap.", "",
          "Hosts to allow for the probes above: " + ", ".join(f"`{h}`" for h in sorted(set(ALLOW_HOSTS.values()))) + ".",
          ""]  # fmt: skip
    return "\n".join(L)


def backfill_status(res, meta, state_check) -> str:
    b, cov, st = res["backfill"], res["coverage"], res["state"]
    L = header("Historical backfill status", res, meta)
    L += ["## Verified observations", "",
          f"- Archive (pinned, Phase 1) last tournament start: **{cov['archive_last_tournament_date']}**.",
          f"- Gap audited: {cov['weeks_total']} weeks from {cov['first_week']} to the last completed week before "
          f"{cov['as_of']}.",
          f"- Real records retrieved for the gap: **{cov['retrieved_total']}**; validated: **{cov['validated_total']}**. "
          f"The newest record of any reachable candidate source starts {cov['newest_candidate_record_date']}.",
          f"- TML records imported through the unchanged Phase 4A path (all outside the gap): {b['provider_records']}"
          f" records, {b['provider_players']} players, parse errors {b['parse_errors']}; reconciliation quarantine "
          + ", ".join(f"{q['reason']} {q['len']}" for q in b["reconciliation_quarantine"]) +
          f"; accepted {b['accepted_records']}. Nothing was accepted, because every player mapping awaits review "
          "(see identity_status.md); in any case these matches are already in the archive.", "",
          "## Week-by-week coverage", "",
          f"Expected events are **inferred** ({cov['calendar_basis']}); they are an estimate, not a verified "
          "schedule. No week is reported complete.", ""]  # fmt: skip
    L += tbl(["week", "expected events (inferred)", "observed", "retrieved", "validated", "quarantined",
              "stats complete", "unresolved ids", "status"],
             [[w["week"], ", ".join(w["expected_events_inferred"]) or "-", ", ".join(w["observed_events"]) or "-",
               w["retrieved"], w["validated"], w["quarantined"], f(w["complete_stats_share"]), w["unresolved_identities"],
               w["status"]] for w in cov["weeks"]])  # fmt: skip
    L += ["", f"Totals: {cov['expected_events_inferred_total']} expected events (inferred, "
          f"{cov['expected_reference_matches_total']} matches in the reference season); {cov['weeks_no_data']} of "
          f"{cov['weeks_total']} weeks have no data. Source freshness: newest candidate record "
          f"{cov['newest_candidate_record_date']}.", "",
          "## State reconstruction", "",
          f"- Starting Phase 4A state: `{st['starting_state_snapshot_id']}` (match component "
          f"`{st['starting_matches_component']}`).",
          f"- New source snapshots: {', '.join('`' + x[:28] + '…`' for x in st['new_source_snapshots']) or 'none'}.",
          f"- Consumed backfill rows: {st['validated_backfill_rows']}; Elo updates: {st['elo_updates']}; "
          f"serve/return updates: {st['serve_return_updates']}.",
          f"- Final workspace state: `{st['final_state_snapshot_id']}` (match component "
          f"`{st['final_matches_component']}`). Match state unchanged: **{st['match_state_unchanged']}**. "
          f"Latest released result batch: the archive's (tournaments to {st['archive_last_tournament_date']}).",
          f"- Backfill run twice on the same snapshot: identical summaries: **{st['deterministic_rerun']}**."]  # fmt: skip
    if state_check:
        runs = state_check["runs"]
        L += [f"- Full engine reconstruction (frozen Phase 2 Elo + Phase 3A features over {runs[0]['rows']:,} matches) "
              f"run {len(runs)} times: state-table hashes " + ", ".join(f"`{r['state_table_hash']}`" for r in runs) +
              f" ({', '.join(str(r['seconds']) + ' s' for r in runs)}): deterministic **{state_check['deterministic']}**, "
              f"peak RSS {state_check['peak_rss_mb']:.0f} MB."]  # fmt: skip
    L += ["", "Because nothing in the gap was validated, the reconstructed state equals the Phase 4A state. An "
          "incomplete backfill is not operational readiness.", "",
          "## Blockers and next actions", "",
          "- No reachable authorized source covers 2026-05-25 onward (see provider_access.md).",
          "- Once a source is authorized: import → review identities → run `tennis-data ops-run` → check this table "
          "week by week against an authoritative calendar.", ""]  # fmt: skip
    return "\n".join(L)


def statistical_compatibility(res, meta, cfg) -> str:
    s = res["compatibility"]
    c, acct = s["comparison"], s["accounting"]
    L = header("Statistical compatibility: TML-Database vs the pinned archive", res, meta)
    L += ["## Verified observations (real records, overlap window " + " to ".join(s["window"] or ["n/a"]) + ")", "",
          f"- TML records in the window: {acct['candidate_records']}; matched to exactly one archive match: "
          f"**{acct['matched']}**; a player not mapped (ambiguous/new): {acct['unmapped_player']}; no archive match: "
          f"{acct['no_archive_match']} (by level {s.get('candidate_unmatched_by_level')}); several archive matches: "
          f"{acct['several_archive_matches']}.",
          f"- Archive matches in the window without a TML counterpart: {s['archive_only']} of "
          f"{s['archive_matches_in_window']} (by level {s.get('archive_only_by_level')}). Coverage differs between "
          "the sources (Davis Cup, qualifying-level inclusion).",
          f"- Winner agreement {f(c['winner_agreement_share'], 4)}; status agreement {f(c['status_agreement_share'], 4)}"
          f" (disagreements {c['status_disagreements']}); identical score strings {f(c['score_agreement_share'], 4)}.",
          "",
          "Player mapping for this study uses the Phase 4A high-confidence mappings (name + birth date) *for "
          "analysis only*; they still await approval before any state use.", "",
          "## Field-by-field agreement (candidate − archive, per player, matched matches)", ""]  # fmt: skip
    L += tbl(["field", "comparable", "exact agreement", "mean diff", "|diff| p50 / p90 / p99 / max", "TML missing",
              "archive missing", "compatible"],
             [[k, v["comparable"], f(v["exact_agreement"], 4), f(v["mean_difference"], 3),
               " / ".join(f(x, 0) for x in v["abs_difference_p50_p90_p99_max"] or []),
               v["candidate_missing"], v["archive_missing"], "yes" if v["compatible"] else "**no**"]
              for k, v in c["fields"].items()])  # fmt: skip
    L += ["", f"Thresholds (fixed before the study, `config/operations.toml`): at least "
          f"{cfg.min_matched_observations} comparable values and exact agreement ≥ {cfg.min_exact_agreement}. "
          f"Fields required by the Phase 3A estimators: {', '.join(c['required_fields'])}.", "",
          "## Systematic differences", "",
          f"- {c['core_field_mismatch_matches']} matched matches differ in at least one required field; "
          f"{c['mismatches_explained_by_swapped_sides']} of them exactly by winner and loser statistics being "
          "swapped in one source.",
          f"- The differences are concentrated: {c['events_fully_consistent']} of {c['events_compared']} events agree "
          "exactly on every required field. Events with differences:", ""]  # fmt: skip
    L += tbl(
        ["event", "matched", "with differences", "share"],
        [[e["event"], e["matches"], e["core_mismatches"], f(e["share"], 2)] for e in c["events_with_mismatches"]],
    )
    L += ["", "- Winner disagreements: " + ("; ".join(f"{w['tournament']} {w['round']}: TML `{w['candidate_score']}` "
          f"vs archive `{w['archive_score']}`" for w in c["winner_disagreements"]) or "none") + ".",
          "- Agreement by status (completed / retired) is in `results.json` (`fields_by_status`).", "",
          "## Verdict", "",
          f"**Statistics compatible: {c['statistics_compatible']}.** The large differences sit in a few events, "
          "notably Grand Slams. The likely cause is different upstream statistics feeds, which the data cannot "
          "prove. Grand Slams carry a large share of the serve/return evidence, and excluding the "
          "disagreeing events now would be a choice made after seeing the result. TML serve statistics therefore "
          "stay **out of the frozen feature engine**: they remain labelled `tml_unverified`, which Phase 4A excludes "
          "from statistics. A results-only use is possible once identities are approved: winners agree in "
          f"{f(c['winner_agreement_share'], 4)} of matched matches.", "",
          "## Unverified", "", "- No statistics from any gap-period source could be compared: none is reachable.", ""]  # fmt: skip
    return "\n".join(L)


def identity_status(res, meta) -> str:
    idn = res["identity"]
    L = header("Player identity status", res, meta)
    L += [
        "## Verified observations (Phase 4A identity resolver on real TML players)",
        "",
        f"Players: {idn['players']}.",
        "",
    ]
    L += tbl(
        ["category", "method", "usable for state", "players"],
        [[r["category"], r["method"], r["usable"], r["len"]] for r in idn["by_category"]],
    )
    L += ["", "- `high_confidence` (unique exact name + matching birth date) is **not** auto-approved "
          "(`auto_approve_high_confidence = false`); a reviewer must add the mappings to "
          "`config/identity_overrides.toml`. None was added in Phase 5A.",
          "- Matches involving any unresolved player are held (`identity_unresolved`), so no mapping can contaminate "
          "Elo or serve/return state.", "",
          "## Defect found and fixed: name order and spelling variants", "",
          "Three TML players were classified as **new players** before the fix, although the archive knows them: "
          "it stores the family name in the first-name field or splits it differently, so the surname index found "
          "no candidate. A new canonical ID would have split their histories, and the new-player registry is "
          "append-only, so the error would have persisted. Phase 4A identity now also searches names written in "
          "another order, and the same birth date with a related name, and holds such players as **ambiguous** "
          "(`name_order_or_spelling_variant`). Regression tests: `tests/test_identity_regressions.py`.", "",
          "## Review queue (ambiguous and new players; nothing is approved automatically)", ""]  # fmt: skip
    L += tbl(["provider id", "category", "method", "TML name", "born", "IOC", "archive candidates"],
             [[r["provider_player_id"], r["category"], r["method"], r["name"], r["birth_date"] or "-", r["country"] or "-",
               "; ".join(f"{c['id']} {c['name']} ({c['birth_date'] or '?'}, {c['country'] or '?'})" for c in r["candidates"])
               or "-"] for r in idn["review_queue"]])  # fmt: skip
    L += [
        "",
        "## Next actions",
        "",
        "- A reviewer approves or rejects each high-confidence and ambiguous mapping "
        "(overrides with reviewer and note); then the backfill is re-run.",
        "",
    ]
    return "\n".join(L)


def schedule_coverage(res, meta) -> str:
    sch = res["schedule"]
    L = header("Schedule, actual-start and outcome coverage", res, meta)
    L += ["## Verified observations", "",
          f"- Verified schedule sources: **{', '.join(sch['verified_sources']) or 'none'}**. Real fixtures ingested: "
          f"{sch['fixtures']}.",
          f"- Sourced actual-start feeds: **{', '.join(sch['actual_start_sources']) or 'none'}**.",
          "- No reachable source states completion times or publishes revisions of outcomes for the gap or the "
          "future.", "",
          "## Fixture-only tests (synthetic, CI)", "",
          "- The Phase 4A exchange format carries fixtures (`scheduled`/`postponed`/`cancelled`) with "
          "`scheduled_start_at` (timezone required, never assumed), provider match ids, round, format, surface and "
          "players. Tests cover postponement, withdrawal (cancelled) and replacement players through the identity "
          "and ledger lifecycle.",
          "- Scheduled start and actual start are separate fields. Phase 4C uses only *sourced* actual starts, takes "
          "the earliest when sources disagree, flags the disagreement, and leaves timing unresolved without one.", "",
          "## Unverified capabilities", "",
          "- Sportradar, api-tennis and RapidAPI document schedules and match status. None is reachable, so no "
          "response layout is verified; actual-start semantics (first point vs walk-on) must be checked against "
          "real responses.", "",
          "## Blockers and next actions", "",
          "- Authorize one schedule/live provider (network allowlist + credentials), verify its layout on real "
          "responses, and record two independent actual-start sources where possible (disagreements are flagged, "
          "never averaged).", ""]  # fmt: skip
    return "\n".join(L)


def readiness_report(res, meta) -> str:
    r = res["readiness"]
    L = header("Operational readiness", res, meta)
    L += [f"## Verdict: **{r['verdict']}**", "",
          f"Failing required checks: {len(r['failing_required'])} of {len(r['required_checks'])}. The evaluator "
          f"changed the status gate: **{r['gate_changed_by_evaluator']}** (gate: backfill "
          f"{r['gate_after_evaluation'].get('backfill')}, prospective predictions "
          f"{r['gate_after_evaluation'].get('prospective_predictions')}).", ""]  # fmt: skip
    L += tbl(
        ["dimension", "check", "status", "evidence", "remediation"],
        [[c["dimension"], c["id"], c["status"], c["evidence"], c["remediation"] or "-"] for c in r["checks"]],
    )
    L += ["", "## Recommendation", "",
          "**Do not activate prospective predictions.** Keep `backfill = \"INCOMPLETE\"` and "
          "`prospective_predictions = \"DISABLED\"`. No configuration change is proposed: activation can only be "
          "proposed when every required check passes, and even then it needs explicit approval in a reviewed "
          "commit.", "",
          "Remediation, in order:", "",
          "1. Authorize a current source (provider_access.md): network allowlist and credentials, or a licensed export.",
          "2. Verify its layout and statistics on real records (statistical_compatibility.md method); results-only "
          "if statistics differ.",
          "3. Review identities (identity_status.md) and backfill every gap week; confirm the calendar.",
          "4. Authorize a schedule/actual-start provider.",
          "5. Configure an RFC 3161 TSA (and optionally an independent checkpoint repository) "
          "(docs/operational_data.md).",
          "6. Re-run `tennis-data ops-run`; only a full PASS allows proposing activation.", ""]  # fmt: skip
    return "\n".join(L)


def write_all(res, meta, cfg, state_check=None) -> list[Path]:
    out = Path(cfg.reports_dir)
    out.mkdir(parents=True, exist_ok=True)
    pages = {"provider_access.md": provider_access(res, meta, cfg), "backfill_status.md": backfill_status(res, meta, state_check),
             "statistical_compatibility.md": statistical_compatibility(res, meta, cfg),
             "identity_status.md": identity_status(res, meta), "schedule_coverage.md": schedule_coverage(res, meta),
             "readiness_report.md": readiness_report(res, meta)}  # fmt: skip
    paths = []
    for name, text in pages.items():
        (out / name).write_text(text.rstrip("\n") + "\n")
        paths.append(out / name)
    return paths
