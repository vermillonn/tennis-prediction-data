"""Dry run of an owner-supplied export: validation set, backfill set, cross-checks, identity proposal, simulation.

``dry_run`` writes ``<export>/dry_run.json`` and renders ``reports/operations/owner_export_<label>.md``. It never
changes Phase 4A's outputs, the identity overrides or the status gate: the production backfill needs the owner's
approval of the identity mappings first.
"""

from __future__ import annotations

import json
import shutil
from datetime import date

from tennis_data.operations import backfill_plan, crosscheck, exports, pipeline


def dry_run(cfg, label: str, as_of: date) -> dict:
    d = exports.export_dir(cfg, label)
    man = json.loads((d / "manifest.json").read_text())
    full, gap = exports.export_config(cfg, label), exports.export_config(cfg, label, gap_only=True)
    a = pipeline.run(full, as_of, probe=False, fetch=False)["results"]
    g = pipeline.run(gap, as_of, probe=False, fetch=False)["results"]
    src = d / "workspace" / "tml" / label
    tml_files = {n: (src / n).read_bytes() for n in full.tml["files"]}
    tml = crosscheck.tml_records(tml_files)
    since = gap.archive_last_week
    cross = {}
    for f in man["files"]:
        if f["role"] == "crosscheck_season":
            cross["season"] = crosscheck.corroborate(
                tml, crosscheck.season_records((d / "files" / f["stored_as"]).read_bytes()), since
            )
        if f["role"] == "crosscheck_vbt":
            cross["vbt"] = crosscheck.corroborate(
                tml, crosscheck.vbt_records((d / "files" / f["stored_as"]).read_bytes()), since
            )
    events = [e for e in crosscheck.completeness(tml, since) if e["start"] > since.isoformat()]
    fprop = backfill_plan.identity_proposal(full)
    gprop = backfill_plan.identity_proposal(gap)
    corr = {r["provider_player_id"]: r for r in fprop["proposed"]}
    for r in gprop["proposed"]:
        c = corr.get(r["provider_player_id"])
        if c:
            r.update(
                {k: c[k] for k in ("overlap_matches_confirming", "overlap_matches_contradicting", "evidence_class")}
            )
    gprop["corroborated"] = sum(1 for r in gprop["proposed"] if r["overlap_matches_confirming"]
                                and not r["overlap_matches_contradicting"])  # fmt: skip
    gprop["contradicted"] = sum(1 for r in gprop["proposed"] if r["overlap_matches_contradicting"])
    gprop["uncorroborated"] = len(gprop["proposed"]) - gprop["corroborated"] - gprop["contradicted"]
    backfill_plan.write_proposal(d / "identity_overrides.proposed.toml", gprop)
    shutil.rmtree(d / "simulation", ignore_errors=True)
    sim = backfill_plan.simulate(gap, d / "identity_overrides.proposed.toml", d / "simulation")
    recon = d / "simulation_state_reconstruction.json"
    vdup = d / "validation_duplicate_check.json"
    out = {"label": label, "as_of": as_of.isoformat(), "manifest": man, "validation_set": a, "backfill_set": g,
           "crosscheck": cross, "events": events,
           "identity_proposal": {k: v for k, v in gprop.items() if k != "proposed"},
           "review_queue": g["identity"]["review_queue"], "simulation": sim,
           "simulation_state": json.loads(recon.read_text()) if recon.exists() else None,
           "validation_duplicate_check": json.loads(vdup.read_text()) if vdup.exists() else None}  # fmt: skip
    (d / "dry_run.json").write_text(json.dumps(out, indent=1, sort_keys=True, default=str) + "\n")
    return out


def _t(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |"
                                                                       for r in rows]  # fmt: skip


def render(out: dict, cfg) -> str:
    man, a, g, sim = out["manifest"], out["validation_set"], out["backfill_set"], out["simulation"]
    comp = a["compatibility"]["comparison"]
    acct = a["compatibility"]["accounting"]
    sm = sim["summary"]
    L = [f"# Owner-supplied 2026 export: dry-run backfill report ({out['label']})", "",
         f"As of {out['as_of']}. Generated by `tennis-data ops-export-dry-run`. **No production state was changed**: "
         "every player mapping still needs the owner's approval, so the authorized backfill has not been executed. "
         "Numbers marked SIMULATION assume the proposed mappings are approved and come from a sandbox copy.", "",
         "## 1. Provenance", "",
         f"Origin (owner's statement): {man['origin']}. Acquired {man['acquired_on']}; registered {man['registered_at']}. "
         f"Licence status: **{man['licence_status']}**. Redistribution: {man['redistribution']}.", ""]  # fmt: skip
    L += _t(["file", "role", "bytes", "SHA-256"], [[f["original_name"], f["role"], f"{f['bytes']:,}", f"`{f['sha256']}`"]
                                                  for f in man["files"]])  # fmt: skip
    conv = g["conversion"]
    L += ["", "## 2. Semantics of the primary file (`2026.csv`)", "",
          "- Same layout and identifiers as TML (Sackmann columns, ATP player codes, `ATP_Database.csv` player file, "
          "UTF-8); converted by the Phase 5A TML converter.",
          f"- **`tourney_date` holds each match's own date, not the event start** ({conv['events_with_per_match_dates']} "
          "events have several dates). The frozen batching needs event starts, so the event start is the earliest match "
          "date of the event: same weekly batch as the archive for 28 of 29 overlapping non–Davis Cup events (United "
          "Cup starts on a Friday). Davis Cup ties are dated inconsistently in the archive itself.",
          "- The \"1,360 records from tournaments beginning May 25 onward\" are 108 Roland Garros 2026 matches (an event "
          f"the archive already holds completely, 127 matches) plus **{conv['matches']:,} records of {conv['tournaments']} "
          "events starting after the archive** (the backfill set).",
          "- `2026_challenger.csv` (Challenger) is registered for provenance only and never parsed: it is outside the "
          "frozen rating population. The two other result files are used only for cross-checks.", "",
          "## 3. Validation against the archive (January–May 2026 overlap)", "",
          f"- Matched to exactly one archive match (same players, round, event week): **{acct['matched']:,}** of "
          f"{acct['candidate_records']:,} overlap records (unmapped player {acct['unmapped_player']}, no archive match "
          f"{acct['no_archive_match']}, several {acct['several_archive_matches']}).",
          f"- Winner and loser: agreement {comp['winner_agreement_share']:.4f}. Score strings identical: "
          f"{comp['score_agreement_share']:.4f}. Status agreement {comp['status_agreement_share']:.4f}.",
          "- Player identifiers: TML ATP codes, mapped through names and birth dates (§6). No archive ID is claimed by "
          "the file.",
          "- Tournament identity: TML IDs are not zero-padded (`2026-339` vs archive `2026-0339`); Phase 4A matches "
          "tournaments by normalized name, level, year and start date instead."]  # fmt: skip
    v = out.get("validation_duplicate_check")
    if v:
        L += [f"- Duplicate detection, tested by simulating an import of the whole file: {v['duplicates_detected']:,} "
              f"duplicates of archive matches recognised, {v['contradicts_archive']} contradictions quarantined (7 differ "
              "only in score notation, i.e. how retirements and match tie-breaks are written; one is a genuine score "
              "difference), and "
              f"**{v['overlap_rows_accepted_as_new']} archive-period records missed** because the tournament is named "
              "differently (`Monte Carlo` vs `Monte Carlo Masters`: 55) or Davis Cup teams are listed in the other order "
              "(28). They would have been counted twice. **The backfill set therefore excludes every event inside the "
              "archive period**; the overlap is validation data only. (Phase 4A limitation for Phase 5B: tournament "
              "matching by exact normalized name.)"]  # fmt: skip
    L += ["", "## 4. Serve-statistics compatibility (predeclared thresholds)", ""]
    L += _t(["field", "comparable", "exact agreement", "compatible"],
            [[k, x["comparable"], f"{x['exact_agreement']:.4f}", "yes" if x["compatible"] else "**no**"]
             for k, x in comp["fields"].items()])  # fmt: skip
    ev = comp["events_with_mismatches"]
    L += ["", f"**Statistics compatible: {comp['statistics_compatible']}** (threshold {cfg.min_exact_agreement} on "
          f"{', '.join(comp['required_fields'])}). All {comp['core_field_mismatch_matches']} differing matches are in: "
          + "; ".join(f"{e['event']} {e['core_mismatches']}/{e['matches']}" for e in ev) + ". Every other overlapping "
          "event agrees exactly, which again points to a different statistics feed for Grand Slams (as in the 2025 "
          "TML study). Under the predeclared rule the source fails as a whole: **results only**. The statistics stay "
          "labelled `tml_unverified` and Phase 4A removes them (`stats_definition_incompatible`); outcomes are kept. "
          "A per-event rule would need a reviewed protocol change decided before looking at gap data.", "",
          "## 5. Coverage cross-check (events starting after 2026-05-25)", ""]  # fmt: skip
    for k, nm in (
        ("season", "`2026-atp-season.csv` (ATP Tour rows)"),
        ("vbt", "`valuebetennis-matchs-2026.csv` (ATP main-tour categories)"),
    ):
        c = out["crosscheck"].get(k)
        if c:
            ac = c["accounting"]
            L.append(f"- {nm}: {ac.get('matched', 0):,} of {ac.get('tml_records', 0):,} TML records have a unique counterpart "
                     f"(same players, match dates within a day); winner agrees in {ac.get('winner_agrees', 0):,}, differs "
                     f"in {ac.get('winner_differs', 0)}.")  # fmt: skip
    dis = out["crosscheck"].get("vbt", {}).get("winner_disagreements", [])
    if dis:
        L.append(
            "- ValueBetTennis winner disagreements (all retirements; the season file agrees with TML on each): "
            + "; ".join(f"{x['tournament']} {x['round']} {x['date']} TML `{x['tml_score']}`" for x in dis)
            + "."
        )
    L += ["- Rows in the other sources without a TML counterpart are qualifying draws (e.g. 112 per Grand Slam, 12 per "
          "250 event), plus Vienna and Basel, which started on 2026-10-26 and are still being played. No completed "
          "main-tour event of the gap is missing from TML.", "",
          "Per-event completeness of the backfill set (knockout draw of size *n* has *n* − 1 matches):", ""]  # fmt: skip
    L += _t(["start", "event", "level", "matches", "draw", "final", "status"],
            [[e["start"], e["tournament"], e["level"], e["matches"], e["draw_size"], "yes" if e["has_final"] else "-",
              e["status"]] for e in out["events"] if e["level"] != "D"])  # fmt: skip
    dc = [e for e in out["events"] if e["level"] == "D"]
    L += ["", f"Davis Cup: {len(dc)} ties, {sum(e['matches'] for e in dc)} singles rubbers (not judged: dead rubbers are "
          "often not played).", "", "## 6. Identities (conservative Phase 4A process)", ""]  # fmt: skip
    ip = out["identity_proposal"]
    L += [f"Backfill set: {g['identity']['players']} players. High-confidence (unique exact name + birth date), awaiting "
          f"approval: **{ip['corroborated'] + ip['uncorroborated'] + ip['contradicted']}**, of which {ip['corroborated']} "
          f"are also corroborated by archive-overlap matches (same pair, round, week, winner) and {ip['uncorroborated']} "
          f"rest on name + birth date only; {ip['contradicted']} contradicted. They are written to the *proposed* "
          "overrides file `data/operations/exports/<label>/identity_overrides.proposed.toml` (reviewer = PENDING; not "
          "applied). Ambiguous and new players are listed below and are not proposed.", ""]  # fmt: skip
    L += _t(["provider id", "category", "method", "name", "born", "IOC", "archive candidates"],
            [[r["provider_player_id"], r["category"], r["method"], r["name"], r["birth_date"] or "-", r["country"] or "-",
              "; ".join(f"{c['id']} {c['name']} ({c['birth_date'] or '?'})" for c in r["candidates"]) or "-"]
             for r in out["review_queue"]])  # fmt: skip
    gb = g["backfill"]
    L += ["", "## 7. Dry-run backfill (production configuration, nothing approved)", "",
          f"- Records: {gb['provider_records']:,}; parse errors {gb['parse_errors']}; reconciliation: "
          + ", ".join(f"{q['reason']} {q['len']:,}" for q in gb["reconciliation_quarantine"]) +
          f"; accepted **{gb['accepted_records']}**. Without approved identities nothing can enter the state.", "",
          "## 8. SIMULATION: the backfill with the proposed identities approved", ""]  # fmt: skip
    L += _t(["item", "count"], [
        ["new verified main-tour matches (Phase 1 validated)", f"**{sim['gap_validated']:,}**"],
        ["  by level", ", ".join(f"{k} {v}" for k, v in sim["gap_by_level"].items())],
        ["duplicates of the archive", sim["duplicates_of_archive"]],
        ["held (ambiguous player identity)", sim["quarantine_by_reason"].get("identity_unresolved", 0)],
        ["other quarantine", sum(v for k, v in sim["quarantine_by_reason"].items() if k != "identity_unresolved")],
        ["statistics removed (incompatible definition)", sim["notes_by_reason"].get("stats_definition_incompatible", 0)],
        ["expected Elo updates (frozen eligibility)", f"**{sim['gap_elo_updates']:,}**"],
        ["not Elo-eligible (frozen policy)", ", ".join(f"{k} {v}" for k, v in sim["gap_excluded_from_elo"].items())],
        ["results-only / results + statistics", f"{sim['gap_validated'] - sim['gap_with_complete_stats_in_state']:,} / "
                                                f"{sim['gap_with_complete_stats_in_state']}"],
        ["serve/return updates", sim["gap_stats_eligible"]],
        ["latest release batch / state-eligible through", f"{sim['latest_release_batch']} / {sim['state_eligible_through']}"],
        ["simulated state snapshot", f"`{sim['state_snapshot_id']}` (match component `{sm['state_components']['matches']}`)"],
        ["deterministic re-run", sim["deterministic_rerun"]],
    ])  # fmt: skip
    ss = out.get("simulation_state")
    if ss:
        L += ["", f"Full frozen-engine reconstruction of the simulated state, run {len(ss['runs'])} times: "
              + ", ".join(f"`{r['state_table_hash']}` ({r['rows']:,} matches, {r['seconds']} s)" for r in ss["runs"])
              + f": deterministic **{ss['deterministic']}**. Elo and feature configuration hashes "
              f"`{ss['runs'][0]['elo_configuration_hash']}` / `{ss['runs'][0]['feature_configuration_hash']}` (unchanged "
              "engines)."]  # fmt: skip
    L += ["", "## 9. Remaining gaps after an approved backfill", "",
          f"- {sim['quarantine_by_reason'].get('identity_unresolved', 0)} matches involving ambiguous players stay out "
          "until those identities are reviewed.",
          "- Serve/return state stays at the archive's end (Roland Garros 2026): the Phase 4A freshness check "
          "`last_point_statistics` fails for any upcoming match, which blocks prospective predictions by itself.",
          "- Vienna and Basel (week of 2026-10-26) are in progress; no ongoing feed exists for later weeks.",
          "- Schedules, actual start times and an RFC 3161 timestamp authority are still missing (readiness_report.md).", "",
          "## 10. Actions requiring owner approval", "",
          "1. Confirm the licence of each file for research use (status recorded as *not verified*).",
          "2. Review `identity_overrides.proposed.toml` and the review queue above; copy approved mappings, with your "
          "name as reviewer, into `config/identity_overrides.toml`.",
          "3. Approve executing the production backfill: `tennis-data prospective-import <export>/workspace_gap/"
          "converted.json --format tennis-fixture-provider-1`, then `tennis-data prospective-backfill`, with a baseline "
          "copy of `data/prospective/` kept first.",
          "4. Decide whether serve statistics may ever be used per event (a protocol change made before looking at gap "
          "statistics); until then the backfill is results-only.", ""]  # fmt: skip
    return "\n".join(L)
