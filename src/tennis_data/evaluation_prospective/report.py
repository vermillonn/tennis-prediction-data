"""Deterministic Markdown reports rendered from ``results.json`` (plus the package's provenance claims).

Reports contain no wall-clock time. Every number is recomputed by ``verify.verify_package`` before a report is
accepted; a report is a rendering of the results, never a source of them.
"""

from __future__ import annotations

from pathlib import Path

from tennis_data.evaluation_prospective.coverage import pct
from tennis_data.evaluation_prospective.safeio import write_new

BANNERS = {
    "PROSPECTIVE": "**Genuine prospective evaluation.** Only PROSPECTIVE ledger records can enter the scored cohorts.",
    "SYNTHETIC": "**SYNTHETIC DEMONSTRATION: NOT PROSPECTIVE EVIDENCE.** Every forecast and outcome in this report "
                 "is synthetic, generated by `evaluation_prospective.demo` to exercise the pipeline. No number here "
                 "describes M4A's real performance.",
    "HISTORICAL_REPLAY": "**HISTORICAL EXPLORATORY RESULTS: NOT PROSPECTIVE EVIDENCE.** Forecasts were reconstructed "
                         "after the fact (HISTORICAL_REPLAY); outcomes may have been known when they were made.",
}  # fmt: skip
LEVELS_DOC = """| trust level | meaning |
|---|---|
| INVALID | integrity verification failed, or an anchor or retained checkpoint contradicts the snapshot |
| LOCAL_ONLY | the chain verifies internally, but no external evidence verifies (fixture anchors, unreachable or unverifiable remotes, untrusted TSA). Says nothing about *when* events were written |
| EXTERNALLY_PUBLISHED | the exact checkpoint bytes were read back from an independently hosted commit. Publication time and the host's administrative independence are **not** attested |
| INDEPENDENTLY_TIMESTAMPED | an RFC 3161 token, verified against a TSA trusted by the verifier, proves the checkpoint (and every event up to its sequence) existed no later than the attested time |"""


def f(x, nd=4, sign=False):
    if x is None:
        return "n/a"
    if isinstance(x, float):
        return f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return str(x)


def p(d: dict) -> str:
    if d["denominator"] == 0:
        return f"{d['n']} / 0"
    return f"{d['n']} / {d['denominator']} ({d['pct']:.1f}%)"


def table(rows: list[dict], cols: list[tuple[str, str]], fmt=None) -> list[str]:
    fmt = fmt or {}
    out = ["| " + " | ".join(h for h, _ in cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join(fmt.get(k, f)(r.get(k)) for _, k in cols) + " |")
    return out


def header(res: dict, prov: dict, title: str) -> list[str]:
    led, idn = res["inputs"]["ledger"], res["inputs"]
    gates = prov.get("status_gates") or {}
    lines = [f"# {title}", "", BANNERS[res["cohort_mode"]], "",
             "Generated by `tennis-data eval-run` from the audit package's `results.json`; regenerate and check "
             "with `tennis-data eval-verify` (every number is recomputed from the package inputs).", "",
             "| input | value |", "|---|---|"]  # fmt: skip
    if "ledger_id" in led:
        lines += [f"| ledger id | `{led['ledger_id']}` |", f"| ledger head | seq {led['head_seq']}, `{led['head_hash']}` |",
                  f"| snapshot export SHA-256 | `{led['snapshot_sha256']}` |"]  # fmt: skip
    else:
        lines += [f"| ledger | **{led['status']}** |"]
    o = idn["outcomes"]
    lines += [f"| outcome snapshot SHA-256 | `{o['outcome_snapshot_sha256']}` ({o['records']} records, "
              f"id `{o['snapshot_id']}`) |",
              f"| evaluation cutoff | {idn['evaluation_cutoff'] or 'none (every event in the snapshot)'} |",
              f"| protocol | `{res['protocol']['version']}`, hash `{res['protocol_hash'][:16]}` |",
              f"| cohort mode | {res['cohort_mode']} |",
              f"| approved model | `{res['protocol']['approved_model_id']}`, frozen hash "
              f"`{res['protocol']['approved_frozen_hash']}`, configuration hash "
              f"`{res['protocol']['approved_configuration_hash']}` |",
              f"| anchor verification | {idn['anchor_verification']}; {len(idn['anchor_records'])} anchor record(s), "
              f"{len(idn['trusted_checkpoints'])} retained trusted checkpoint(s), "
              f"{len(idn['tsa_trust_anchor_sha256'])} TSA trust anchor(s) |",
              f"| git commit (claimed by the package) | `{prov.get('git_commit') or 'unknown'}` |"]  # fmt: skip
    if gates:
        lines.append("| operational status (claimed by the package) | " + "; ".join(
            f"{k} = **{v}**" for k, v in gates.items()) + " |")  # fmt: skip
    return lines + [""]


def metrics_block(s: dict, label: str, mode: str = "PROSPECTIVE") -> list[str]:
    if s["n"] == 0:
        return [f"No forecasts in the {label}: **no metric is reported.**", ""]
    m, e, d = s["models"]["M4A"], s["models"]["Elo"], s["paired"]
    lines = [f"{label}: **{s['n']} matches** (M4A and surface Elo scored on exactly the same matches).", "",
             "| model | log loss | Brier | accuracy | ECE | mean P(A) | observed A |", "|---|---|---|---|---|---|---|"]  # fmt: skip
    names = (("M4A (raw, frozen)", "surface Elo (committed baseline)") if mode != "SYNTHETIC" else
             ("synthetic 'M4A' probabilities", "synthetic 'Elo' probabilities"))  # fmt: skip
    for name, x in zip(names, (m, e), strict=True):
        lines.append(f"| {name} | {f(x['log_loss'])} | {f(x['brier'])} | {f(x['accuracy'])} | {f(x['ece'])} | "
                     f"{f(x['mean_predicted_a'])} | {f(x['observed_a'])} |")  # fmt: skip
    lines += ["", f"Paired ΔLL = LL(M4A) − LL(Elo) = **{f(d['log_loss_diff'], 5, True)}** (negative favours M4A); "
              f"ΔBrier = {f(d['brier_diff'], 5, True)}; M4A has the lower loss on "
              f"{100 * d['share_matches_m4a_better']:.1f}% of matches.", ""]  # fmt: skip
    return lines


def prospective_report(res: dict, prov: dict) -> str:
    c, sc, mode = res["coverage"], res["scores"], res["cohort_mode"]
    integ = res["integrity"]
    title = {"PROSPECTIVE": "Prospective evaluation report", "SYNTHETIC": "Synthetic demonstration: evaluation report",
             "HISTORICAL_REPLAY": "Historical exploratory evaluation report"}[mode]  # fmt: skip
    L = header(res, prov, title)
    prim = sc["primary"]["n"]
    L += ["## Headline", ""]
    if mode == "PROSPECTIVE" and prim == 0:
        L += [f"**Eligible genuine prospective forecasts: 0.** No prospective performance metric exists, and none is "
              f"reported. Prediction commitments in the snapshot: {c['total_predictions']}; PROSPECTIVE records: "
              f"{c['cohort_mode_predictions']}.", ""]  # fmt: skip
    else:
        L += [f"Primary cohort (scorable and independently timestamped before the actual start): **{prim}** "
              f"matches. Operational cohort (scorable, weaker timing evidence): **{sc['operational']['n']}**.", ""]  # fmt: skip
    L += ["## The eight questions", "",
          f"1. **Recorded before the match?** Of {c['selected_forecasts']['n']} selected {mode} forecasts, "
          f"{sum(1 for r in res['classification'] if r['selected'] and r['timing'] == 'PRE_START')} were committed "
          f"before a sourced actual start (host clock), "
          f"{sum(1 for r in res['classification'] if r['selected'] and r['timing'] == 'LATE')} at or after it, and "
          f"{sum(1 for r in res['classification'] if r['selected'] and r['timing'] == 'UNRESOLVED')} have no "
          f"actual-start evidence (unresolved).",
          f"2. **Independently verifiable commitment history?** Chain integrity: "
          f"{'no ledger' if integ['ok'] is None else ('verified' if integ['ok'] else '**FAILED**')}; snapshot head "
          f"evidence: **{res['anchoring']['snapshot_head_evidence'] or 'n/a'}**. Forecasts by evidence level: "
          + (", ".join(f"{k} {v['n']}" for k, v in c["by_evidence_level"].items()) or "none") + ".",
          f"3. **Trustworthy outcomes?** {len(res['outcomes'])} matches reconciled; unresolved (pending, disputed, "
          f"identity mismatch, unknown) for the cohort: {len(res['unresolved_outcomes'])}.",
          f"4. **Eligible for scoring?** Scorable: {p(c['scorable'])} of selected forecasts; primary cohort "
          f"{p(c['primary_cohort'])}; operational cohort {p(c['operational_cohort'])}.",
          "5. **M4A vs frozen surface Elo?** See below; reported only for non-empty cohorts.",
          "6. **Calibration?** `calibration_report.md` (no recalibration is fitted).",
          "7. **Coverage, exclusions and failures?** `coverage_report.md`, `integrity_report.md`.",
          f"8. **Statistical uncertainty?** Primary: {res['uncertainty']['primary']['status']}; operational: "
          f"{res['uncertainty']['operational']['status']} (`uncertainty_report.md`).", "",
          "## Primary cohort", ""]  # fmt: skip
    L += metrics_block(sc["primary"], "Primary cohort", mode)
    L += ["## Operational cohort (not independently timestamp-verified)", "",
          "Scorable forecasts whose commitment time rests on the ledger host clock and, at best, a non-attested "
          "external publication. These results must not be described as independently timestamp-verified.", ""]  # fmt: skip
    L += metrics_block(sc["operational"], "Operational cohort", mode)
    L += ["## Retirements (secondary analysis, never in the primary score)", ""]
    L += metrics_block(sc["retirement_secondary"], "Retirement analysis", mode)
    L += ["## Selection and scoring policy (frozen in the protocol)", "",
          f"- Cohort mode {mode}; approved model `{res['protocol']['approved_model_id']}`; primary slot "
          f"`{res['protocol']['primary_forecast_slot']}`; selection `{res['protocol']['selection_policy']}` (the first "
          "admissible forecast per match, decided before outcomes; a voided or late selection is not replaced).",
          f"- Scored outcomes {res['protocol']['scored_outcomes']}; retirements `{res['protocol']['retirement_policy']}`; "
          f"outcome policy `{res['protocol']['outcome_policy']}`; actual-start evidence required: "
          f"{res['protocol']['require_actual_start_evidence']}; probability clip {res['protocol']['probability_clip']} "
          "for both models; no probability transformation is fitted.", ""]  # fmt: skip
    return "\n".join(L)


def coverage_report(res: dict, prov: dict) -> str:
    c = res["coverage"]
    L = header(res, prov, "Coverage and exclusion report")
    L += ["## Flow", "", "| step | forecasts |", "|---|---|"] + [f"| {s['step']} | {s['n']} |" for s in c["flow"]]
    L += ["", f"Events considered: {c['events_considered']}; matches with events: {c['matches']}.", "",
          "## Final classification (mutually exclusive; denominator: all prediction commitments)", "",
          "| category | forecasts |", "|---|---|"]  # fmt: skip
    L += [f"| {k} | {p(v)} |" for k, v in c["by_category"].items()]
    L += ["", "## By mode", "", "| mode | forecasts |", "|---|---|"] + [
        f"| {k} | {p(v)} |" for k, v in c["by_mode"].items()
    ]
    L += [
        "",
        "## Flags (overlapping; denominator: all prediction commitments)",
        "",
        "| flag | forecasts |",
        "|---|---|",
    ]
    L += [f"| {k} | {p(v)} |" for k, v in c["flags"].items()] or ["| (none) | |"]
    L += ["", "## Evidence level of the commitments", "", "| level | forecasts |", "|---|---|"]
    L += [f"| {k} | {p(v)} |" for k, v in c["by_evidence_level"].items()] or ["| (none) | |"]
    L += ["", f"## Cohorts (denominator: {c['selected_forecasts']['n']} selected {c['cohort_mode']} forecasts)", "",
          f"- selected: {p(c['selected_forecasts'])} of {c['cohort_mode']} records",
          f"- admissible (pre-start verified or outcome pending): {p(c['admissible_forecasts'])} of {c['cohort_mode']} records",
          f"- scorable: {p(c['scorable'])}", f"- primary cohort: {p(c['primary_cohort'])}",
          f"- operational cohort: {p(c['operational_cohort'])}",
          f"- retirement secondary analysis: {p(c['retirement_secondary'])}", "",
          f"## Voided predictions ({len(res['voids'])}; every void stays visible)", ""]  # fmt: skip
    L += table(res["voids"], [("seq", "seq"), ("match", "match_id"), ("mode", "mode"), ("reason", "reason_code"),
                              ("actor", "actor"), ("category", "category")]) if res["voids"] else ["None."]  # fmt: skip
    L += ["", f"## Unresolved outcomes ({len(res['unresolved_outcomes'])})", ""]
    L += table([{**u, "flags": ", ".join(u["flags"]) or "-", "sources": ", ".join(u["sources"]) or "-"}
                for u in res["unresolved_outcomes"]],
               [("match", "match_id"), ("outcome", "outcome"), ("sources", "sources"), ("flags", "flags")]) \
        if res["unresolved_outcomes"] else ["None."]  # fmt: skip
    ex = res["exclusions"]
    L += ["", f"## Exclusions of {c['cohort_mode']} records ({len(ex)}; full list in `tables/exclusions.csv`)", ""]
    shown = [{**e, "flags": ", ".join(e["flags"]) or "-"} for e in ex[:100]]
    L += table(shown, [("seq", "seq"), ("match", "match_id"), ("category", "category"), ("outcome", "outcome"),
                       ("timing", "timing"), ("flags", "flags")]) if ex else ["None."]  # fmt: skip
    if len(ex) > 100:
        L += ["", f"… {len(ex) - 100} more in `tables/exclusions.csv`."]
    return "\n".join(L) + "\n"


def integrity_report(res: dict, prov: dict) -> str:
    integ, an = res["integrity"], res["anchoring"]
    L = header(res, prov, "Integrity and checkpoint report")
    L += ["## Hash chain", ""]
    if integ["ok"] is None:
        L += [f"**{integ['status']}.** Nothing to verify; no forecast can be evaluated.", ""]
    else:
        L += [f"- Phase 4B verifier (`verify_events`): **{'verified' if integ['ok'] else 'FAILED'}**; events "
              f"{integ['events']}; head seq {integ['head_seq']}, `{integ['head_hash']}`.",
              f"- Lifecycle replay: {'valid' if integ.get('lifecycle_ok') else 'invalid'}; anchor and retained-checkpoint "
              f"evidence consistent: {integ.get('evidence_ok')}.", ""]  # fmt: skip
        if integ["issues"]:
            L += table(integ["issues"][:50], [("seq", "seq"), ("code", "code"), ("detail", "detail")]) + [""]
        L += [f"In-chain checkpoint events: {len(integ['in_chain_checkpoints'])}"
              + (f" ({sum(1 for c in integ['in_chain_checkpoints'] if c['ok'])} consistent)" if integ[
                  "in_chain_checkpoints"] else "") + ".", ""]  # fmt: skip
    L += ["## External anchors", "", LEVELS_DOC, ""]
    if an["anchors"]:
        L += table([{**a, "problems": "; ".join(a["problems"]) or "-"} for a in an["anchors"]],
                   [("record", "source"), ("seq", "checkpoint_sequence"), ("backend", "backend"), ("level", "level"),
                    ("receipt", "receipt_status"), ("attested time", "attested_time"),
                    ("claimed publication time (host clock, not evidence)", "claimed_published_at"),
                    ("problems", "problems")])  # fmt: skip
    else:
        L += ["**No anchor record was supplied.** Every commitment is at most LOCAL_ONLY: the chain proves internal "
              "consistency, not when events were written."]  # fmt: skip
    cov = an["coverage"]
    L += ["", f"Coverage: published through seq {cov['published_through_seq']}; independently timestamped through seq "
          f"{cov['timestamped_through_seq']}; invalid anchors {cov['invalid_anchors']}; forked sequences "
          f"{cov['forked_sequences'] or 'none'}. Snapshot head evidence: **{an['snapshot_head_evidence'] or 'n/a'}**.",
          "", "## Retained trusted checkpoints", ""]  # fmt: skip
    if an["trusted_checkpoints"]:
        L += table([{**t, "problems": "; ".join(t["problems"]) or "-"} for t in an["trusted_checkpoints"]],
                   [("file", "source"), ("seq", "sequence"), ("consistent", "ok"), ("problems", "problems")])  # fmt: skip
    else:
        L += ["None supplied. A complete rewrite of the chain cannot be detected without a checkpoint retained (or "
              "published) before the rewrite."]  # fmt: skip
    L += ["", "## Limits of this evidence", "",
          "- `recorded_at` comes from the ledger host's clock; a hash chain fixes order and content, not time.",
          "- A GitHub commit proves the checkpoint bytes were in that repository; its commit date is set by the "
          "client and the repository's administrators can rewrite or delete history (force pushes). It is "
          "publication, not trusted timestamping.",
          "- An RFC 3161 token proves existence no later than its time only for the TSA the verifier chose to trust, "
          "and only for events at or before the checkpoint's sequence.", ""]  # fmt: skip
    return "\n".join(L)


def calibration_report(res: dict, prov: dict) -> str:
    L = header(res, prov, "Calibration and subgroup report")
    L += ["Calibration is measured, never fitted: M4A is scored raw (uncalibrated, as frozen) and Elo as committed.",
          "Subgroups are pre-declared in the protocol and all are listed; groups below "
          f"{res['protocol']['min_subgroup_matches']} matches show counts only (inference inconclusive).", ""]  # fmt: skip
    for cohort in ("primary", "operational"):
        s = res["scores"][cohort]
        L += [f"## {cohort.capitalize()} cohort ({s['n']} matches)", ""]
        if s["n"] == 0:
            L += ["No matches: no calibration table.", ""]
            continue
        for model in ("M4A", "Elo"):
            L += [f"### {model} reliability (ECE {f(s['models'][model]['ece'])}, Brier {f(s['models'][model]['brier'])})",
                  ""]  # fmt: skip
            L += table(res["calibration"][cohort][model],
                       [("bin", "bin"), ("lower", "bin_lower"), ("upper", "bin_upper"), ("n", "n"),
                        ("mean predicted", "mean_predicted"), ("observed", "observed"),
                        ("observed − predicted", "observed_minus_predicted")])  # fmt: skip
            L.append("")
        L += ["### M4A probability distribution", ""]
        L += table(s["probability_distribution"], [("lower", "bin_lower"), ("upper", "bin_upper"), ("n", "n_m4a")])
        L += ["", "### Subgroups", ""]
        for g, rows in res["subgroups"][cohort].items():
            L += [f"**{g}**", ""]
            L += table(rows, [("group", "group"), ("n", "n"), ("LL M4A", "ll_m4a"), ("LL Elo", "ll_elo"),
                              ("ΔLL", "d_ll"), ("Brier M4A", "brier_m4a"), ("Brier Elo", "brier_elo"),
                              ("status", "status")])  # fmt: skip
            L.append("")
    return "\n".join(L)


def uncertainty_report(res: dict, prov: dict) -> str:
    pr = res["protocol"]
    L = header(res, prov, "Uncertainty report")
    L += [f"Paired block bootstrap of ΔLL = LL(M4A) − LL(Elo): {pr['bootstrap_samples']} resamples, seed "
          f"{pr['bootstrap_seed']}, clusters {pr['clusters']}. No interval is reported below "
          f"{pr['min_matches_inferential']} matches or {pr['min_blocks_inferential']} blocks.", "",
          "Week- and tournament-level resampling does not capture dependence through players who recur across "
          "weeks and tournaments; intervals are, if anything, too narrow. A single week, tournament or short run "
          "of results is not evidence of a difference.", ""]  # fmt: skip
    for cohort in ("primary", "operational"):
        u = res["uncertainty"][cohort]
        L += [f"## {cohort.capitalize()} cohort ({u['n']} matches): {u['status']}", ""]
        for kind, e in u["intervals"].items():
            if e.get("status") == "reported":
                L.append(f"- {kind} blocks ({e['blocks']}): ΔLL {f(e['log_loss_diff'], 5, True)}, 95% CI "
                         f"[{f(e['ll_ci95'][0], 5, True)}, {f(e['ll_ci95'][1], 5, True)}]; ΔBrier "
                         f"{f(e['brier_diff'], 5, True)}, 95% CI [{f(e['brier_ci95'][0], 5, True)}, "
                         f"{f(e['brier_ci95'][1], 5, True)}]; {e['verdict']}.")  # fmt: skip
            else:
                L.append(f"- {kind}: {e['status']}")
        if u["seasons"]:
            L += ["", "Season-level (descriptive only):", ""]
            L += table(u["seasons"], [("season", "season"), ("n", "n"), ("ΔLL", "d_ll"), ("status", "status")])
        L.append("")
    return "\n".join(L)


RENDERERS = {"prospective_report.md": prospective_report, "coverage_report.md": coverage_report,
             "integrity_report.md": integrity_report, "calibration_report.md": calibration_report,
             "uncertainty_report.md": uncertainty_report}  # fmt: skip


def render_all(res: dict, prov: dict) -> dict[str, bytes]:
    return {name: (fn(res, prov).rstrip("\n") + "\n").encode("utf-8") for name, fn in RENDERERS.items()}


def write_reports(res: dict, prov: dict, out: Path) -> list[Path]:
    return [write_new(Path(out) / name, data) for name, data in render_all(res, prov).items()]


__all__ = ["render_all", "write_reports", "pct"]
