"""Generate docs/data_dictionary.md from the schema and rule registry (single source of truth)."""

from __future__ import annotations

from pathlib import Path

from tennis_data.config import PROJECT_ROOT
from tennis_data.normalization.schema import CANONICAL_COLUMNS, QUARANTINE_EXTRA, ROUND_ORDER
from tennis_data.normalization.score import MATCH_STATUSES
from tennis_data.validation.rules import RULES

DICTIONARY_PATH = PROJECT_ROOT / "docs" / "data_dictionary.md"

_QUARANTINE_DESCRIPTIONS = {
    "quarantine_reasons": "Sorted error codes that sent the row to quarantine",
    "quarantine_categories": "Sorted categories of those codes (schema, identity, stats, duplicate, conflict, ...)",
    "duplicate_of": "For duplicate_record: match_id of the kept first occurrence",
    "raw_record": "JSON of the original 49 source fields exactly as read (whitespace-trimmed strings)",
}

_STATUS_NOTES = {
    "completed": "score is a complete list of sets",
    "retired": "score contains RET: a player retired during the match",
    "walkover": "W/O or Walkover: not played; never use as a played result",
    "default": "DEF / Def.: a player was defaulted",
    "abandoned": "ABD / ABN: match abandoned",
    "unfinished": "'Played and unfinished' / 'In Progress'",
    "unknown": "score empty, 'NA', 'UNK', garbled with '?', or otherwise unparseable",
}


def _dtype(d) -> str:
    return str(d).replace("String", "string")


def render_dictionary() -> str:
    lines = [
        "# Data dictionary",
        "",
        "_Generated by `tennis-data docs` from `src/tennis_data/normalization/schema.py` and "
        "`src/tennis_data/validation/rules.py`. Do not edit by hand; `tests/test_schema.py` fails if it is stale._",
        "",
        "## Validated match table",
        "",
        "Location: `data/validated/matches/season=<YYYY>/part-0.parquet` (also contains the `season` column). "
        "One row per singles match. DuckDB view: `matches`.",
        "",
        "Player A and player B are assigned by `sha256(match_id)` (first byte even -> lower ID is A), "
        "which is deterministic and independent of the result. Columns prefixed `player_a_` / `player_b_` "
        "refer to those players; the source's winner/loser perspective survives only in `winner_id`, "
        "`player_a_won` and `score`.",
        "",
        "| column | type | nullable | group | description |",
        "|---|---|---|---|---|",
    ]
    for c in CANONICAL_COLUMNS:
        lines.append(
            f"| `{c.name}` | {_dtype(c.dtype)} | {'yes' if c.nullable else 'no'} | {c.group} | {c.description} |"
        )
    lines += [
        "",
        "## Quarantine table",
        "",
        "Location: `data/quarantine/matches.parquet`. DuckDB view: `quarantine`. Same columns as the validated "
        "table (any of which may be null, since quarantined rows can lack required values), plus:",
        "",
        "| column | type | description |",
        "|---|---|---|",
    ]
    for name, dtype in QUARANTINE_EXTRA.items():
        lines.append(f"| `{name}` | {_dtype(dtype)} | {_QUARANTINE_DESCRIPTIONS[name]} |")
    lines += ["", "## `match_status` values", "", "| value | meaning |", "|---|---|"]
    lines += [f"| `{s}` | {_STATUS_NOTES[s]} |" for s in MATCH_STATUSES]
    lines += ["", "## `round_order`", "", "| round | order |", "|---|---|"]
    lines += [f"| {r} | {o} |" for r, o in ROUND_ORDER.items()]
    lines += [
        "",
        "`round_order` sorts matches within an event. It is an ordinal, not a time: RR matches of one event "
        "share a value, and qualifying-round order relative to main-draw rounds is approximate.",
        "",
        "## Temporal semantics (leakage)",
        "",
        "- The source has **no match dates or times**. `match_date` and `match_start_time` are always null and are "
        "never inferred from `tournament_date`. `time_precision` is `tournament_week` for every row.",
        "- `tournament_date` is the event start (usually a Monday); every match of an event shares it. Order "
        "matches with `(tournament_date, tournament_id, round_order)`; matches in the same round of the same "
        "event are not ordered relative to each other.",
        "- Ranks, ranking points, seeds, entry and age are as of `tournament_date`, i.e. known before the event. "
        "Height and hand are biographical values of unknown measurement date.",
        "- Serve statistics describe the match itself: they are outcomes, never pre-match features.",
        "",
        "## Validation rules",
        "",
        "`error` rows go to quarantine; `warning` codes are listed in `quality_flags` and the row is kept.",
        "",
        "| code | severity | category | description |",
        "|---|---|---|---|",
    ]
    lines += [f"| `{r.code}` | {r.severity} | {r.category} | {r.description} |" for r in RULES]
    return "\n".join(lines) + "\n"


def write_dictionary(path: Path = DICTIONARY_PATH) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_dictionary())
    return path
